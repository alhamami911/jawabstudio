for (const [file, p] of Object.entries(N)) {
  const j = JSON.parse(readFileSync(dir + file, "utf8"));
  j.opening = p.opening;
  j.closing = p.closing;
  if (p.say.length !== j.steps.length) throw new Error(`${file}: ${p.say.length} say entries vs ${j.steps.length} steps`);
  j.steps.forEach((s, i) => {
    const want = p.say[i];
    if (Array.isArray(s.say) !== Array.isArray(want) || (Array.isArray(want) && want.length !== s.say.length)) throw new Error(`${file} step ${i}: say shape mismatch`);
    s.say = want;
  });
  writeFileSync(dir + file, JSON.stringify(j, null, 2));
  console.log("updated", file);
}
