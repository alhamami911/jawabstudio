// يطبّق العبارات على حلقات سلسلة قبل كتابتها؛ يرفض مصفوفة لا يطابق طولها عدد الخطوات (فهرس منزاح = عبارة في غير موضعها)
export function applyCaps(seriesId, eps) {
  eps.forEach((ep, i) => {
    const caps = CAPS[`${seriesId}/${i + 1}`];
    if (!caps) return;
    if (caps.length !== ep.steps.length) throw new Error(`captions ${seriesId}/${i + 1}: ${caps.length} captions for ${ep.steps.length} steps`);
    ep.keyCaptions = true;
    ep.steps = ep.steps.map((st, k) => (caps[k] ? { ...st, caption: caps[k] } : st));
  });
}
